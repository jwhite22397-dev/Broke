export function getJobById(id: string): Job | undefined {
  return JOBS.find(j => j.id === id);
}

export function getJobsForCareerPath(careerPathId: string): Job[] {
  return JOBS.filter(j => j.careerPathId === careerPathId).sort((a, b) => a.tier - b.tier);
}

export function getEntryLevelJobs(): Job[] {
  return JOBS.filter(j => j.tier === 1 && j.requiredExperience === 0);
}

const ACADEMIC_LADDER: EducationLevel[] = [
  'no_diploma', 'ged', 'high_school', 'some_college', 'associate', 'bachelor', 'master', 'doctorate',
];

function educationSatisfies(player: EducationLevel, required: EducationLevel[]): boolean {
  if (required.includes(player)) return true;
  if (player === 'trade_cert') {
    return required.some(level => level === 'no_diploma' || level === 'ged' || level === 'high_school' || level === 'trade_cert');
  }
  const playerRank = ACADEMIC_LADDER.indexOf(player);
  if (playerRank < 0) return false;
  return required.some(level => {
    const requiredRank = ACADEMIC_LADDER.indexOf(level);
    return requiredRank >= 0 && playerRank >= requiredRank;
  });
}

export function getEligibleJobs(
  education: EducationLevel,
  experienceMonths: number,
  skills: Skills
): Job[] {
  return JOBS.filter(job => {
    if (!educationSatisfies(education, job.requiredEducation)) return false;
    if (job.requiredExperience > experienceMonths) return false;
    
    for (const [skill, required] of Object.entries(job.skillRequirements)) {
      const current = skills[skill as keyof Skills] ?? 0;
      if (current < required) return false;
    }
    return true;
  });
}
